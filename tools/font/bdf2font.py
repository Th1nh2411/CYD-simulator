"""Convert a BDF bitmap font into the firmware's gfx::Font table (C++).

usage: python tools/font/bdf2font.py tools/font/galmuri/Galmuri11.bdf src/app/gfx/fonts/ko11.cpp kFontKo11

Source (not in git): Galmuri11.bdf and LICENSE.txt from
https://github.com/quiple/galmuri (v2.40.4, dist/), SIL Open Font License 1.1.
The license travels with the table as src/app/gfx/fonts/LICENSE-Galmuri.txt.

Keeps printable ASCII, the KS X 1001 repertoire that matters for messages
(2,350 Hangul syllables, Hangul compatibility jamo, the two symbol rows), the
Vietnamese letters (Capri answers in the language she is spoken to) and
nothing else. Glyph bitmaps are packed as one bit stream, rows top to bottom,
MSB first. y offsets are measured down from the top of the line.
"""
import sys


def ksx1001_codes():
    codes = set(range(0x20, 0x7F))
    rows = [0xA1, 0xA2, 0xA4] + list(range(0xB0, 0xC9))  # symbols, jamo, Hangul syllables
    for hi in rows:
        for lo in range(0xA1, 0xFF):
            try:
                ch = bytes([hi, lo]).decode("euc-kr")
            except UnicodeDecodeError:
                continue
            if len(ch) == 1:
                codes.add(ord(ch))
    return codes


VIETNAMESE = "àáảãạăằắẳẵặâầấẩẫậđèéẻẽẹêềếểễệìíỉĩịòóỏõọôồốổỗộơờớởỡợùúủũụưừứửữựỳýỷỹỵ"


def wanted_codes():
    return ksx1001_codes() | {ord(c) for c in VIETNAMESE + VIETNAMESE.upper()}


def read_bdf(path):
    glyphs, cur, bitmap = {}, None, None
    for line in open(path, encoding="utf-8", errors="replace"):
        parts = line.split()
        if not parts:
            continue
        key = parts[0]
        if key == "STARTCHAR":
            cur, bitmap = {}, None
        elif cur is None:
            continue
        elif key == "ENCODING":
            cur["code"] = int(parts[1])
        elif key == "DWIDTH":
            cur["adv"] = int(parts[1])
        elif key == "BBX":
            cur["w"], cur["h"], cur["xo"], cur["yo"] = map(int, parts[1:5])
        elif key == "BITMAP":
            bitmap = []
        elif key == "ENDCHAR":
            cur["rows"] = bitmap or []
            glyphs[cur["code"]] = cur
            cur = None
        elif bitmap is not None:
            bitmap.append(int(key, 16))
    return glyphs


def main():
    src, out, name = sys.argv[1], sys.argv[2], sys.argv[3]
    font = read_bdf(src)
    wanted = sorted(c for c in wanted_codes() if c in font and c <= 0xFFFF)
    glyphs = [font[c] for c in wanted]
    # The line is the Korean one: Vietnamese stacked marks rise above its top (by `above`)
    lined = [font[c] for c in ksx1001_codes() if c in font]
    top = max(g["yo"] + g["h"] for g in lined)  # baseline distance from the line top
    bottom = min(g["yo"] for g in lined)
    above = max(g["yo"] + g["h"] for g in glyphs) - top

    bits, entries = [], []
    for g in glyphs:
        offset = len(bits)
        row_bytes = (g["w"] + 7) // 8
        for r in g["rows"]:
            for x in range(g["w"]):
                bits.append((r >> (row_bytes * 8 - 1 - x)) & 1)
        entries.append((g["adv"], g["w"], g["h"], g["xo"], top - (g["yo"] + g["h"]), offset))
    if len(bits) >= 1 << 20:
        raise SystemExit("bitmap too large for 20-bit offsets")
    data = bytearray((len(bits) + 7) // 8)
    for i, b in enumerate(bits):
        if b:
            data[i >> 3] |= 0x80 >> (i & 7)

    hangul = sum(1 for c in wanted if 0xAC00 <= c <= 0xD7A3)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/font/bdf2font.py from Galmuri11 (Copyright (c) 2019-2025 Lee Minseo,\n")
        f.write("// SIL Open Font License 1.1, see LICENSE-Galmuri.txt next to this file). Do not edit.\n")
        f.write(f"// {len(wanted)} glyphs ({hangul} Hangul syllables), {len(data)} bytes of bitmap.\n\n")
        f.write('#include "app/gfx/font.h"\n\nnamespace gfx {\n\nnamespace {\n\n')
        f.write("constexpr uint16_t kCodes[] = {\n")
        for i in range(0, len(wanted), 12):
            f.write("    " + " ".join(f"0x{c:04X}," for c in wanted[i:i + 12]) + "\n")
        f.write("};\n\nconstexpr Glyph kGlyphs[] = {\n")
        for i in range(0, len(entries), 4):
            f.write("    " + " ".join("{%d, %d, %d, %d, %d, %d}," % e for e in entries[i:i + 4]) + "\n")
        f.write("};\n\nconstexpr uint8_t kBits[] = {\n")
        for i in range(0, len(data), 16):
            f.write("    " + " ".join(f"0x{b:02X}," for b in data[i:i + 16]) + "\n")
        f.write("};\n\n}  // namespace\n\n")
        f.write(f"const Font {name} = {{kCodes, kGlyphs, kBits, {len(wanted)}, {top - bottom}, {top}, {above}}};\n\n")
        f.write("}  // namespace gfx\n")
    print(f"{out}: {len(wanted)} glyphs, line {top - bottom} px, baseline {top}, {above} px above, bitmap {len(data)} B")


if __name__ == "__main__":
    main()
